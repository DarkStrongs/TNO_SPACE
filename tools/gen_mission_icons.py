THICK=False   # r95r 试过 2px 加粗，糊成一团，保留 1px
def draw(name):
    f=blank(); rows=[r for r in G[name].strip('\n').split('\n')]
    H=len(rows); W=len(rows[0]); ox=(22-W)//2; oy=(22-H)//2
    px=f.load()
    for y,r in enumerate(rows):
        assert len(r)==W,(name,y,len(r))
        for x,ch in enumerate(r):
            if ch=='#': px[ox+x,oy+y]=HI
            if ch=='#' and THICK and x+1<W and r[x+1]=='.' and (x+2>=W or r[x+2]=='.') and ox+x+1<21: px[ox+x+1,oy+y]=HI   # 竖笔加粗到 2px，同旧图
    # 1px 过渡：亮线四邻的暗像素压一点中间色（同旧图 + 号）
    src=f.copy(); sp=src.load()
    for y in range(1,21):
        for x in range(1,21):
            if sp[x,y]==HI: continue
            n=sum(sp[x+dx,y+dy]==HI for dx,dy in ((1,0),(-1,0),(0,1),(0,-1)))
            if n>=2: px[x,y]=MID
    return f
