def ld(p):
    b=open(p,'rb').read(); h,w=struct.unpack('<2I',b[12:20]); return Image.frombytes('RGBA',(w,h),b[128:128+w*h*4],'raw','BGRA')
def save_dds(im,p):
    w,h=im.size
    hdr=b'DDS '+struct.pack('<7I',124,0x100F,h,w,w*4,0,0)+b'\0'*44+struct.pack('<8I',32,0x41,0,32,0xFF0000,0xFF00,0xFF,0xFF000000)+struct.pack('<5I',0x1000,0,0,0,0)
    assert len(hdr)==128; open(p,'wb').write(hdr+im.convert('RGBA').tobytes('raw','BGRA'))
